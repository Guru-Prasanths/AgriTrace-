let currentTnFilter = 'all';
let currentTnSearch = '';
let currentTnDistrict = 'all';
let currentTnSort = 'default';
let displayedCount = 50;
const PAGE_SIZE = 50;

function initTnDatasets() {
  renderCategoryBadges();
  renderDatasetGrid();
}

function renderCategoryBadges() {
  const filterTabs = document.getElementById('tnFilterTabs');
  if (!filterTabs) return;

  const total = TN_AGRICULTURAL_DATASETS.length;
  const isTa = typeof getCurrentLanguage === 'function' && getCurrentLanguage() === 'ta';

  let html = `<button class="tn-filter-tab ${currentTnFilter === 'all' ? 'active' : ''}" data-filter="all" onclick="setTnFilter('all', this)">
    <span>${isTa ? 'அனைத்தும்' : 'All'}</span>
    <span class="tn-cat-badge">${total}</span>
  </button>`;

  TN_AGRICULTURAL_CATEGORIES.forEach(cat => {
    const count = TN_AGRICULTURAL_DATASETS.filter(d => d.category === cat.id).length;
    const active = currentTnFilter === cat.id ? 'active' : '';
    const label = isTa ? cat.labelTa : cat.label;
    html += `<button class="tn-filter-tab ${active}" data-filter="${cat.id}" onclick="setTnFilter('${cat.id}', this)">
      <span>${cat.icon} ${label}</span>
      <span class="tn-cat-badge">${count}</span>
    </button>`;
  });

  filterTabs.innerHTML = html;
}

function setTnFilter(catId, btn) {
  currentTnFilter = catId;
  displayedCount = PAGE_SIZE; // reset pagination on filter change
  document.querySelectorAll('.tn-filter-tab').forEach(b => b.classList.remove('active'));
  if (btn) btn.classList.add('active');
  renderDatasetGrid();
}

function filterTnDatasets() {
  const input = document.getElementById('tnSearchInput');
  currentTnSearch = (input?.value || '').toLowerCase().trim();
  displayedCount = PAGE_SIZE; // reset pagination on search
  renderDatasetGrid();
}

function sortTnDatasets(sortMode) {
  currentTnSort = sortMode;
  renderDatasetGrid();
}

function getFilteredDatasets() {
  let list = TN_AGRICULTURAL_DATASETS.filter(item => {
    const matchCat = currentTnFilter === 'all' || item.category === currentTnFilter;
    const matchSearch = !currentTnSearch || 
      item.cropName.toLowerCase().includes(currentTnSearch) ||
      item.cropTamil.includes(currentTnSearch) ||
      item.title.toLowerCase().includes(currentTnSearch) ||
      item.districts.toLowerCase().includes(currentTnSearch) ||
      item.sourceOrg.toLowerCase().includes(currentTnSearch);
    return matchCat && matchSearch;
  });

  if (currentTnSort === 'crop-asc') {
    list.sort((a, b) => a.cropName.localeCompare(b.cropName));
  } else if (currentTnSort === 'crop-desc') {
    list.sort((a, b) => b.cropName.localeCompare(a.cropName));
  } else if (currentTnSort === 'date-desc') {
    list.sort((a, b) => b.lastUpdated.localeCompare(a.lastUpdated));
  }

  return list;
}

function renderDatasetGrid() {
  const grid = document.getElementById('tnDatasetGrid');
  const counterEl = document.getElementById('tnDatasetCounter');
  const showMoreContainer = document.getElementById('tnShowMoreContainer');
  const showMoreBtn = document.getElementById('tnShowMoreBtn');
  if (!grid) return;

  const filtered = getFilteredDatasets();
  const totalFiltered = filtered.length;
  const toDisplay = filtered.slice(0, displayedCount);

  if (counterEl) {
    const isTa = typeof getCurrentLanguage === 'function' && getCurrentLanguage() === 'ta';
    counterEl.textContent = isTa
      ? `${totalFiltered} தரவுகளில் ${toDisplay.length} காட்டப்படுகிறது`
      : `Showing ${toDisplay.length} of ${totalFiltered} datasets`;
  }

  if (toDisplay.length === 0) {
    grid.innerHTML = `<div class="tn-no-results">
      <div style="font-size:36px;margin-bottom:8px;">🔍</div>
      <h4>No agricultural datasets match your search</h4>
      <p style="color:var(--muted);font-size:14px;">Try searching for a different crop name, district, or select 'All'.</p>
    </div>`;
    if (showMoreContainer) showMoreContainer.style.display = 'none';
    return;
  }

  const isTa = typeof getCurrentLanguage === 'function' && getCurrentLanguage() === 'ta';

  grid.innerHTML = toDisplay.map(item => `
    <div class="parent tn-dataset-parent" onclick="openDatasetDetailModal(${item.id})" style="cursor:pointer;" aria-label="Dataset: ${item.cropName}">
      <div class="card tn-glass-card">
        <div class="logo">
          <span class="circle circle1"></span>
          <span class="circle circle2"></span>
          <span class="circle circle3"></span>
          <span class="circle circle4"></span>
          <span class="circle circle5">
            <span style="font-size:22px;line-height:1;display:block;">${item.icon || '🌾'}</span>
          </span>
        </div>
        <div class="glass"></div>
        <div class="content">
          <span class="title">${item.cropName} <small style="font-size:13px;font-weight:600;opacity:0.85;">(${item.cropTamil})</small></span>
          <span class="text">${item.desc && item.desc.length > 70 ? item.desc.slice(0, 67) + '...' : (item.desc || '')}</span>
        </div>
        <div class="bottom">
          <div class="social-buttons-container">
            <button type="button" class="social-button" title="Category: ${item.categoryLabel}" onclick="event.stopPropagation();">
              <span style="font-size:12px;">📊</span>
            </button>
            <button type="button" class="social-button" title="Districts: ${item.districts}" onclick="event.stopPropagation();">
              <span style="font-size:12px;">📍</span>
            </button>
            <button type="button" class="social-button" title="Updated: ${item.lastUpdated}" onclick="event.stopPropagation();">
              <span style="font-size:12px;">📅</span>
            </button>
          </div>
          <div class="view-more">
            <button type="button" class="view-more-button" onclick="event.stopPropagation(); openDatasetDetailModal(${item.id})">
              ${isTa ? 'விவரம்' : 'View'}
            </button>
            <svg class="svg" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" stroke-width="3" stroke="currentColor" fill="none" stroke-linecap="round" stroke-linejoin="round">
              <path stroke="none" d="M0 0h24v24H0z" fill="none"></path>
              <path d="M9 6l6 6l-6 6"></path>
            </svg>
          </div>
        </div>
      </div>
    </div>
  `).join('');

  // Handle Show More Button
  if (showMoreContainer && showMoreBtn) {
    if (displayedCount < totalFiltered) {
      showMoreContainer.style.display = 'flex';
      const remaining = totalFiltered - displayedCount;
      const nextBatch = Math.min(PAGE_SIZE, remaining);
      showMoreBtn.textContent = isTa
        ? `மேலும் ${nextBatch} தரவுகளைக் காட்டு (மீதம் ${remaining})`
        : `Show More (${nextBatch} more of ${remaining} remaining) ➔`;
      showMoreBtn.disabled = false;
    } else {
      showMoreContainer.style.display = 'none';
    }
  }

  if (typeof initUiverseLeafButtons === 'function') {
    initUiverseLeafButtons();
  }
}

function handleShowMoreDatasets() {
  displayedCount += PAGE_SIZE;
  renderDatasetGrid();
}

function openDatasetDetailModal(datasetId) {
  if (window.floatingNav && typeof window.floatingNav.close === 'function') {
    window.floatingNav.close();
  }

  const item = TN_AGRICULTURAL_DATASETS.find(d => d.id === datasetId);
  if (!item) return;

  const modal = document.getElementById('tnDatasetDetailModal');
  if (!modal) return;

  const isTa = typeof getCurrentLanguage === 'function' && getCurrentLanguage() === 'ta';

  document.getElementById('tnModalCropIcon').textContent = item.icon;
  document.getElementById('tnModalCropName').innerHTML = `${item.cropName} <span style="color:#7B9B3A;margin-left:8px;">${item.cropTamil}</span>`;
  document.getElementById('tnModalCategory').textContent = isTa ? item.categoryLabelTa : item.categoryLabel;
  document.getElementById('tnModalCategory').className = `tn-cat-pill tn-cat-${item.category}`;
  document.getElementById('tnModalTitle').textContent = item.title;
  document.getElementById('tnModalDistricts').textContent = item.districts;
  document.getElementById('tnModalSourceOrg').textContent = item.sourceOrg;
  document.getElementById('tnModalLastUpdated').textContent = item.lastUpdated;
  document.getElementById('tnModalDesc').textContent = item.desc;
  
  const sourceLink = document.getElementById('tnModalSourceLink');
  if (sourceLink) {
    sourceLink.href = item.url;
    sourceLink.target = '_blank';
    sourceLink.rel = 'noopener noreferrer';
  }

  const downloadLink = document.getElementById('tnModalDownloadLink');
  if (downloadLink) {
    downloadLink.href = item.downloadUrl;
    downloadLink.target = '_blank';
    downloadLink.rel = 'noopener noreferrer';
  }

  modal.classList.add('open');
}

function closeDatasetDetailModal() {
  const modal = document.getElementById('tnDatasetDetailModal');
  if (modal) modal.classList.remove('open');
}

